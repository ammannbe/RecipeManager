    private function photoSection(): Section
    {
        return Section::make(__('Photo'))
            ->description(__('Optional: added to the recipe after the import.'))
            ->visible(fn (): bool => $this->jsonPhotos < RecipeJsonSchema::MAX_PHOTOS)
