                    ->visible(fn (): bool => $this->aiPhoto !== null)
                    ->content(fn (): Htmlable => new HtmlString('<img src="'.e(route('import-photos.show', ['filename' => (string) $this->aiPhoto])).'" alt="'.e(__('AI photo')).'" style="max-width: 20rem; width: 100%; border-radius: 0.5rem">')),
                Actions::make([$this->generatePhotoAction(), $this->removeAiPhotoAction()])
                    ->key('photoActions'),
            ]);
    }

    private function removeAiPhotoAction(): Action
    {
        return Action::make('removeAiPhoto')
            ->label(__('Remove AI photo'))
            ->icon(Heroicon::OutlinedTrash)
            ->color('danger')
            ->link()
            ->visible(fn (): bool => $this->aiPhoto !== null)
            ->action(fn () => $this->removeAiPhoto());
    }

    private function removeAiPhoto(): void
    {
        if ($this->aiPhoto !== null) {
            app(RecipePhotos::class)->deleteImportPhoto((int) user()?->getKey(), $this->aiPhoto);
            $this->aiPhoto = null;
        }
    }

    private function generatePhotoAction(): Action
    {
        return Action::make('generatePhoto')
            ->label(__('Generate photo with AI'))
            ->tooltip(__('From the name and the ingredients; replaces a photo generated before.'))
            ->icon(Heroicon::OutlinedSparkles)
            ->color('gray')
            ->visible(fn (): bool => RecipeAssistant::allows(user()))
            ->action(function (): void {
                if (! RecipeAssistant::allows(user())) {
                    return;
                }

                // Errors of the JSON belong to the first step: say it here instead of failing silently.
                try {
                    $parsed = $this->parse();
                } catch (ValidationException $exception) {
                    Notification::make()->warning()->title(__('The AI photo could not be created.'))->body(implode(' ', $exception->validator->errors()->all()))->send();

                    return;
                }

                $name = trim((string) ($this->data['name'] ?? '')) ?: $parsed->name;

                set_time_limit(300);

                try {
                    $binary = app(RecipeAssistant::class)->dishPhoto(
                        user(),
                        $name,
                        array_map(fn (ParsedIngredient $ingredient): string => $ingredient->food, $parsed->allIngredients()),
                    );
                    $extension = app(RecipePhotos::class)->extension($binary, RecipePhotos::MAX_DOWNLOAD_BYTES);
                } catch (AiException|InvalidArgumentException $exception) {
                    Notification::make()->warning()->title(__('The AI photo could not be created.'))->body(__($exception->getMessage()))->send();

                    return;
                }

                $this->removeAiPhoto();
                $this->aiPhoto = app(RecipePhotos::class)->storeImportPhoto((int) user()?->getKey(), $binary, $extension);

                Notification::make()->success()->title(__('Photo created'))->send();
            });
    }

    private function conflictHint(): string
    {
        $conflict = $this->nameConflict();

        if ($conflict === null) {
            return '';
        }

        $suggestion = ['name' => $this->availableName()];

        if (! $conflict->trashed()) {
            return __('Choose another name, for example ":name".', $suggestion);
        }

        return $this->canChangeTrashed($conflict, 'forceDelete') || $this->canChangeTrashed($conflict, 'update')
            ? __('That recipe is in the trash. Choose another name, for example ":name", or delete the recipe in the trash permanently or rename it.', $suggestion)
            : __('That recipe is in the trash and you may not change it. Choose another name, for example ":name".', $suggestion);
    }

    private function useAvailableNameAction(): Action
    {
        return Action::make('useAvailableName')
            ->label(fn (): string => __('Use ":name"', ['name' => $this->availableName()]))
            ->color('gray')
            ->action(function (): void {
                $this->data['name'] = $this->availableName();
                $this->conflicts = [];
            });
    }

    private function forceDeleteTrashedAction(): Action
    {
        return Action::make('forceDeleteTrashed')
            ->label(__('Delete the recipe in the trash permanently'))
            ->color('danger')
            ->icon(Heroicon::OutlinedTrash)
            ->requiresConfirmation()
            ->modalHeading(fn (): string => __('Delete ":name" permanently?', ['name' => (string) $this->nameConflict()?->name]))
            ->modalDescription(__('The recipe and its photos are deleted permanently. This cannot be undone.'))
            ->visible(fn (): bool => $this->canChangeTrashed($this->nameConflict(), 'forceDelete'))
            ->action(function (): void {
                $conflict = $this->nameConflict();

                if (! $this->canChangeTrashed($conflict, 'forceDelete')) {
                    abort(403);
                }

                $conflict?->forceDelete();
                $this->conflicts = [];

                Notification::make()->success()->title(__('The recipe in the trash was deleted permanently.'))->send();
            });
    }

    private function renameTrashedAction(): Action
    {
        return Action::make('renameTrashed')
            ->label(__('Rename the recipe in the trash'))
            ->color('gray')
            ->icon(Heroicon::OutlinedPencilSquare)
            ->visible(fn (): bool => $this->canChangeTrashed($this->nameConflict(), 'update'))
            ->fillForm(fn (): array => ['name' => ($conflict = $this->nameConflict()) !== null
                ? app(RecipeNames::class)->availableName($conflict->name, $conflict->cookbook_id, $conflict->author_id)
                : null])
            ->schema(fn (): array => ($conflict = $this->nameConflict()) !== null ? [RecipeTrashActions::nameInput($conflict)] : [])
            ->action(function (array $data): void {
                $conflict = $this->nameConflict();

                if (! $this->canChangeTrashed($conflict, 'update')) {
                    abort(403);
                }

                $conflict?->update(['name' => trim((string) $data['name'])]);
                $this->conflicts = [];

                Notification::make()->success()->title(__('The recipe in the trash was renamed.'))->send();
            });
    }

    private function canChangeTrashed(?Recipe $conflict, string $ability): bool
    {
        return $conflict !== null && $conflict->trashed() && (bool) user()?->can($ability, $conflict);
    }

    /**
     * The recipe the import would collide with (also in the trash): same name in the cookbook chosen
     * here or named in the JSON, without cookbook among the author's recipes, like the importer.
     * Null while the cookbook or author named in the JSON is undecided; the importer checks anyway.
     */
    private function nameConflict(?string $name = null): ?Recipe
    {
        $name = trim($name ?? (string) ($this->data['name'] ?? ''));
        $scope = $this->nameScope();

        if ($name === '' || $scope === null) {
            return null;
        }

        $key = $name.'|'.implode('|', $scope);

        if (! array_key_exists($key, $this->conflicts)) {
            $this->conflicts[$key] = app(RecipeNames::class)->findDuplicate($name, ...$scope);
        }

        return $this->conflicts[$key];
    }

    private function availableName(): string
    {
        return app(RecipeNames::class)->availableName((string) ($this->data['name'] ?? ''), ...($this->nameScope() ?? [null, null]));
    }

    /**
     * @return array{0: int|null, 1: int|null}|null cookbook and author id
     */
    private function nameScope(): ?array
    {
        $cookbookId = filled($this->data['cookbook_id'] ?? null)
            ? (int) $this->data['cookbook_id']
            : $this->scopeLookupId('cookbook');
        $authorId = $this->scopeLookupId('author') ?? user()?->author_id;

        if ($cookbookId === false || $authorId === false) {
            return null;
        }

        return [$cookbookId, $authorId];
    }

    /**
     * The id of the cookbook or author named in the JSON: matched, or as chosen on this step;
     * false while undecided or to be created (a new one has no recipes yet).
     */
    private function scopeLookupId(string $type): int|false|null
    {
        $lookup = $this->scopeLookups[$type] ?? null;

        if ($lookup === null) {
            return null;
        }

        if ($lookup['id'] !== null) {
            return $lookup['id'];
        }

        $id = data_get($this->data, 'decisions.'.$this->stateKey($lookup['key']).'.id');

        return is_numeric($id) ? (int) $id : false;
    }

    private function confirmStep(): Step
    {
        return Step::make(__('Confirm'))
            ->description(__('Review and import'))
            ->icon(Heroicon::OutlinedCheckCircle)
            ->schema([
                Placeholder::make('summaryPlaceholder')
                    ->hiddenLabel()
                    ->content(fn (): Htmlable => $this->summaryHtml()),
            ]);
    }

    /**
     * @return array<int, Component>
     */
    private function resolutionFields(): array
    {
        if ($this->unresolved === []) {
            return [Text::make(__('Everything could be matched automatically. Nothing to do here.'))];
        }

        $resolver = app(RelationResolver::class);
        $fields = [];

        foreach ($this->unresolved as $item) {
            $type = LookupType::from($item['type']);
            $options = [];

            foreach ($item['suggestions'] as $suggestion) {
                $options[$suggestion['id']] = $suggestion['name'].' — '.__(':score% match', [
                    'score' => $suggestion['score'],
                ]);
            }

            foreach ($resolver->options($type, user()) as $id => $name) {
                $options[$id] ??= $name;
            }

            $statePath = 'decisions.'.$this->stateKey($item['key']);
            $decided = fn (callable $get): bool => $get($statePath.'.create') === true;

            // Left empty, an omittable value is not imported; categories, cookbooks and authors need a choice.
            $select = Select::make($statePath.'.id')
                ->label($type->label())
                ->options($options)
                ->searchable()
                ->native(false)
                ->live()
                ->required(fn (callable $get): bool => ! $item['canOmit'] && ! $decided($get))
                ->disabled($decided);

            if ($item['canOmit']) {
                $select->placeholder(__('Empty: not imported'))
                    ->helperText($this->omitHint($type, $item));
            }

            $components = [$select];

            if ($item['canCreate']) {
                $created = fn (callable $get): bool => $get($statePath.'.create') === true;

                $components[] = Toggle::make($statePath.'.create')
                    ->label($item['createsRequest']
                        ? __('Request ":value"', ['value' => $item['value']])
                        : __('Create ":value" instead', ['value' => $item['value']]))
                    ->helperText($item['createsRequest'] ? (string) __('Usable in your recipe right away; an administrator checks it before others see it.') : null)
                    ->live()
                    ->afterStateUpdated(fn () => $this->checkNewName($type, $statePath))
                    ->default(false);

                $components[] = TextInput::make($statePath.'.name')
                    ->label(__('Name of the new entry'))
                    ->helperText(__('If an entry with this name exists, it is selected instead.'))
                    ->visible($created)
                    ->required($created)
                    ->maxLength($type->maxLength())
                    ->live(onBlur: true)
                    ->afterStateUpdated(function (?string $state) use ($type, $statePath): void {
                        $this->selectExisting($type, (string) $state, $statePath);
                        $this->checkNewName($type, $statePath);
                    })
                    ->columnSpanFull();

                if ($type === LookupType::Food) {
                    $components[] = $this->attributesInput($item['value'], $statePath, $created);
                    $components[] = $this->conversionSection($statePath.'.conversion', $created);
                    $components[] = $this->seasonSection($statePath.'.conversion', $created);
                }
            }

            $fields[] = Section::make($type->label().': '.$item['value'])
                ->description($this->resolutionDescription($item))
                // One column: "Create … instead" below the selection.
                ->schema($components)
                // A unit or attribute only used on omitted ingredients needs no decision.
                ->hidden(fn (callable $get): bool => $this->isObsolete($item, fn (string $path): mixed => $get($path)));
        }

        $fields[] = Actions::make([$this->estimateConversionsAction()])
            ->key('conversionActions')
            ->visible(fn (callable $get): bool => RecipeAssistant::allows(user())
                && $this->newFoods(fn (string $path): mixed => $get($path)) !== []);

        return $fields;
    }

    /**
     * An existing entry with the name typed for a new one is chosen instead of a duplicate.
     *
     * @param  string  $statePath  relative to "data"
     */
    private function selectExisting(LookupType $type, string $name, string $statePath): void
    {
        $existing = trim($name) !== '' ? app(RelationResolver::class)->existing($type, trim($name), user()) : null;

        if ($existing === null) {
            return;
        }

        data_set($this->data, $statePath.'.create', false);
        data_set($this->data, $statePath.'.id', $existing->getKey());

        Notification::make()
            ->info()
            ->title(__('":name" already exists and was selected instead.', ['name' => (string) $existing->getAttribute('name')]))
            ->send();
    }

    /**
     * The same check on "Next" as when leaving the name field: names of existing entries select them.
     */
    private function selectExistingNames(): void
    {
        foreach ($this->unresolved as $item) {
            $statePath = 'decisions.'.$this->stateKey($item['key']);
            $state = (array) data_get($this->data, $statePath, []);

            if ($item['canCreate'] && ($state['create'] ?? false) === true) {
                $this->selectExisting(LookupType::from($item['type']), $this->newName($item, $state), $statePath);
            }
        }
    }

    /**
     * Shows at once that a new name is too long (e.g. a long value taken from the recipe), so the
     * user shortens it; the step and the import refuse it as well.
     *
     * @param  string  $statePath  relative to "data"
     */
    private function checkNewName(LookupType $type, string $statePath): void
    {
        $field = 'data.'.$statePath.'.name';
        $this->resetErrorBag($field);

        if (data_get($this->data, $statePath.'.create') === true && mb_strlen(trim((string) data_get($this->data, $statePath.'.name'))) > $type->maxLength()) {
            $this->addError($field, __('The name may not be longer than :max characters.', ['max' => $type->maxLength()]));
        }
    }

    /**
     * The ingredient attributes of a new food ("gehackt", "fein"), as read from the recipe: changes are
     * written into the JSON of every ingredient with that food, unknown attributes are then matched below.
     *
     * @param  string  $statePath  relative to "data"
     */
    private function attributesInput(string $food, string $statePath, Closure $created): TagsInput
    {
        return TagsInput::make($statePath.'.attributes')
            ->label(__('Attributes'))
            ->helperText(__('Of the ingredients with this food in the recipe, e.g. "gehackt". New ones can be matched or created below.'))
            ->suggestions(fn (): array => IngredientAttribute::query()->visibleTo(user())->orderBy('name')->pluck('name')->all())
            ->nestedRecursiveRules(['max:'.RecipeJsonSchema::MAX_ATTRIBUTE_NAME])
            ->visible($created)
            ->live()
            ->afterStateUpdated(fn (mixed $state) => $this->setFoodAttributes($food, $statePath, (array) $state))
            ->columnSpanFull();
    }

    /**
     * Writes the attributes into every ingredient (and alternative) of the JSON whose food is the given one.
     *
     * @param  string  $statePath  relative to "data"
     * @param  array<int, mixed>  $attributes
     */
    private function setFoodAttributes(string $food, string $statePath, array $attributes): void
    {
        $field = 'data.'.$statePath.'.attributes';
        $this->resetErrorBag($field);

        $attributes = array_values(array_unique(array_filter(
            array_map(fn (mixed $attribute): string => is_string($attribute) ? trim($attribute) : '', $attributes),
            fn (string $attribute): bool => $attribute !== '',
        )));

        foreach ($attributes as $attribute) {
            if (mb_strlen($attribute) > RecipeJsonSchema::MAX_ATTRIBUTE_NAME) {
                $this->addError($field, __('The name may not be longer than :max characters.', ['max' => RecipeJsonSchema::MAX_ATTRIBUTE_NAME]));

                return;
            }
        }

        $json = (string) preg_replace('/^```[a-z]*\s*|\s*```$/i', '', trim((string) ($this->data['json'] ?? '')));
        $recipe = json_decode($json, true);

        if (! is_array($recipe)) {
            return;
        }

        $food = self::foldName($food);
        $apply = function (mixed $ingredients) use (&$apply, $food, $attributes): mixed {
            if (! is_array($ingredients)) {
                return $ingredients;
            }

            foreach ($ingredients as $index => $ingredient) {
                if (! is_array($ingredient)) {
                    continue;
                }

                if (is_string($ingredient['food'] ?? null) && self::foldName($ingredient['food']) === $food) {
                    $ingredients[$index]['attributes'] = $attributes;
                }

                if (isset($ingredient['alternatives'])) {
                    $ingredients[$index]['alternatives'] = $apply($ingredient['alternatives']);
                }
            }

            return $ingredients;
        };

        $recipe['ingredients'] = $apply($recipe['ingredients'] ?? []);

        foreach ((array) ($recipe['ingredient_groups'] ?? []) as $index => $group) {
            if (is_array($group)) {
                $recipe['ingredient_groups'][$index]['ingredients'] = $apply($group['ingredients'] ?? []);
            }
        }

        $previous = $this->data['json'];
        $this->data['json'] = (string) json_encode($recipe, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);

        try {
            $this->parse();
        } catch (ValidationException $exception) {
            $this->data['json'] = $previous;
            $this->parse();
            $this->addError($field, implode(' ', $exception->validator->errors()->all()));
        }
    }

    /**
     * A name compared like the resolver does: case-insensitive, "ß" as "ss".
     */
    private static function foldName(string $name): string
    {
        return str_replace('ß', 'ss', mb_strtolower(trim($name)));
    }

    /**
     * The attributes the recipe gives the ingredients with this food.
     *
     * @return list<string>
     */
    private function foodAttributes(string $food): array
    {
        $attributes = [];

        foreach ($this->parsed?->allIngredients() ?? [] as $ingredient) {
            if (self::foldName($ingredient->food) === self::foldName($food)) {
                array_push($attributes, ...$ingredient->attributes);
            }
        }

        return array_values(array_unique($attributes));
    }

