    /**
     * One AI request for all foods set to "create": fills their conversion and season fields, which stay editable.
     */
    private function estimateConversionsAction(): Action
    {
        return Action::make('estimateConversions')
            ->label(__('Estimate conversions and season with AI'))
            ->tooltip(__('Measure, density, piece weights and season of all new foods'))
            ->icon(Heroicon::OutlinedSparkles)
            ->color('gray')
            ->action(function (): void {
                $foods = $this->newFoods(fn (string $path): mixed => data_get($this->data, $path));

                if ($foods === [] || ! RecipeAssistant::allows(user())) {
                    return;
                }

                $units = [];

                foreach ($this->parse()->allIngredients() as $ingredient) {
                    if ($ingredient->unit !== null) {
                        $units[mb_strtolower($ingredient->food)][$ingredient->unit] = $ingredient->unit;
                    }
                }

                $input = [];

                foreach ($foods as $food) {
                    $input[$food['name']] = array_values($units[mb_strtolower($food['value'])] ?? []);
                }

                try {
                    $estimates = app(RecipeAssistant::class)->conversions(user(), $input);
                } catch (AiException $exception) {
                    Notification::make()->warning()->title(__('The conversions could not be estimated.'))->body(__($exception->getMessage()))->send();

                    return;
                }

                foreach ($foods as $key => $food) {
                    if (isset($estimates[$food['name']])) {
                        $this->fillConversion($key, $estimates[$food['name']]);
                    }
                }

                Notification::make()->success()->title(__('Conversions estimated. Please check them.'))->send();
            });
    }

    /**
     * @param  array{measure: string|null, density: float|null, weights: array<int, float>, season_months: list<int>, storage_months: list<int>}  $estimate
     */
    private function fillConversion(string $key, array $estimate): void
    {
        $conversion = (array) ($this->data['decisions'][$key]['conversion'] ?? []);

        if ($estimate['measure'] !== null) {
            $conversion['measure'] = $estimate['measure'];
        }

        if ($estimate['density'] !== null) {
            $conversion['density'] = $estimate['density'];
        }

        // Months the user already ticked stay; an empty estimate (no Swiss season) changes nothing.
        foreach (['season_months', 'storage_months'] as $field) {
            if ($estimate[$field] !== [] && blank($conversion[$field] ?? null)) {
                $conversion[$field] = $estimate[$field];
            }
        }

        $weights = array_filter((array) ($conversion['weights'] ?? []), 'is_array');

        foreach ($estimate['weights'] as $unitId => $grams) {
            $itemKey = null;

            foreach ($weights as $existingKey => $weight) {
                if ((int) ($weight['unit_id'] ?? 0) === $unitId) {
                    $itemKey = $existingKey;
                }
            }

            $weights[$itemKey ?? (string) Str::uuid()] = ['unit_id' => $unitId, 'grams' => $grams];
        }

        $conversion['weights'] = $weights;
        $this->data['decisions'][$key]['conversion'] = $conversion;
    }

    /**
     * Foods set to "create", by state key, with the parsed value and the name to create.
     *
     * @param  callable(string): mixed  $get  form state by path (relative to "data")
     * @return array<string, array{value: string, name: string}>
     */
    private function newFoods(callable $get): array
    {
        $foods = [];

        foreach ($this->unresolved as $item) {
            $key = $this->stateKey($item['key']);

            if ($item['type'] !== LookupType::Food->value || ! $item['canCreate'] || $get('decisions.'.$key.'.create') !== true) {
                continue;
            }

            $foods[$key] = ['value' => $item['value'], 'name' => $this->newName($item, (array) $get('decisions.'.$key))];
        }

        return $foods;
    }

    /**
     * The name a new entry is created with: as typed on "Resolve", else the parsed value.
     *
     * @param  array{value: string}  $item
     * @param  array<string, mixed>  $state
     */
    private function newName(array $item, array $state): string
    {
        $name = trim((string) ($state['name'] ?? ''));

        return $name !== '' ? $name : $item['value'];
    }

    /**
     * What omitting a value does to the recipe.
     *
     * @param  array{context: array<int, string>}  $item
     */
    private function omitHint(LookupType $type, array $item): string
    {
        return match ($type) {
            LookupType::Food => __('The ingredient is left out (with its alternatives). Check whether the instructions still mention it.'),
            LookupType::Unit => __('The amount stays, without a unit (e.g. "2 Salz" instead of "2 EL Salz").'),
            default => __('Only this entry is left out.'),
        };
    }

    /**
     * Whether a unit or attribute is only used on ingredients whose food is omitted.
     *
     * @param  array{type: string, context: array<int, string>}  $item
     * @param  callable(string): mixed  $get  form state by path (relative to "data")
     */
    private function isObsolete(array $item, callable $get): bool
    {
        if (! in_array($item['type'], [LookupType::Unit->value, LookupType::Attribute->value], true) || $item['context'] === []) {
            return false;
        }

        foreach ($item['context'] as $food) {
            if (! $this->isFoodOmitted($food, $get)) {
                return false;
            }
        }

        return true;
    }

    /**
     * Whether an unresolved food is left out: nothing chosen and not created.
     *
     * @param  callable(string): mixed  $get  form state by path (relative to "data")
     */
    private function isFoodOmitted(string $food, callable $get): bool
    {
        $key = LookupType::Food->value.':'.mb_strtolower($food);

        foreach ($this->unresolved as $item) {
            if ($item['key'] === $key) {
                return $this->isOmitted($item, (array) $get('decisions.'.$this->stateKey($key)));
            }
        }

        return false;
    }

    /**
     * An omittable value with an empty selection that is not created is not imported.
     *
     * @param  array{canOmit: bool}  $item
     * @param  array<string, mixed>  $state
     */
    private function isOmitted(array $item, array $state): bool
    {
        return $item['canOmit'] && ($state['create'] ?? false) !== true && ! is_numeric($state['id'] ?? null);
    }

    /**
     * @param  array{value: string, canCreate: bool, createsRequest: bool, context: array<int, string>, preselectedId: int|null}  $item
     */
    private function resolutionDescription(array $item): string
    {
        $description = $item['preselectedId'] !== null
            ? __('A likely match is preselected. Please verify it.')
            : ($item['createsRequest']
                ? __('Choose an existing entry or request this one.')
                : ($item['canCreate']
                    ? __('Choose an existing entry or create this one.')
                    : __('Choose an existing entry. Only administrators may create new ones.')));

        if ($item['context'] !== []) {
            $description = __('Used on: :ingredients', [
                'ingredients' => implode(', ', $item['context']),
            ]).' — '.$description;
        }

        return $description;
    }

    private function summaryHtml(): Htmlable
    {
        if ($this->summary === []) {
            return new HtmlString('');
        }

        $lines = [];

        $summary = [...$this->summary, __('Recipe') => (string) ($this->data['name'] ?? '')];

        foreach ([...$summary, ...$this->decisionSummary()] as $label => $value) {
            $lines[] = e($label).': '.e($value);
        }

        return new HtmlString('<ul class="list-disc ps-4"><li>'.implode('</li><li>', $lines).'</li></ul>');
    }

    /**
     * Omitted and requested values, so the user sees what the import will leave out.
     *
     * @return array<string, string>
     */
    private function decisionSummary(): array
    {
        $omitted = [];
        $requested = [];
        $existing = [];
        $resolver = app(RelationResolver::class);

        foreach ($this->unresolved as $item) {
            $type = LookupType::from($item['type']);
            $state = $this->data['decisions'][$this->stateKey($item['key'])] ?? [];
            $label = $type->label().' "'.$item['value'].'"';

            if ($this->isObsolete($item, fn (string $path): mixed => data_get($this->data, $path))) {
                continue;
            }

            if ($this->isOmitted($item, $state)) {
                $omitted[] = $label.($item['context'] !== [] && $type !== LookupType::Food
                    ? ' ('.__('on: :ingredients', ['ingredients' => implode(', ', $item['context'])]).')'
                    : '');
            } elseif (($state['create'] ?? false) === true && $item['canCreate']) {
                $name = $this->newName($item, $state);
                $match = $resolver->existing($type, $name, user());

                if ($match !== null) {
                    $existing[] = $type->label().' "'.$match->getAttribute('name').'"';
                } elseif ($item['createsRequest']) {
                    $requested[] = $type->label().' "'.$name.'"';
                }
            }
        }

        return array_filter([
            __('Omitted') => implode('; ', $omitted),
            __('Requested') => implode('; ', array_unique($requested)),
            __('Existing entries used') => implode('; ', array_unique($existing)),
        ]);
    }

    /**
     * @return array<string, string>
     */
    private function buildSummary(ParsedRecipe $parsed): array
    {
        return [
            __('Recipe') => $parsed->name,
            __('Category') => $parsed->category,
            __('Ingredients') => (string) count($parsed->allIngredients()),
            __('Ingredient groups') => (string) count($parsed->groups),
            __('Tags') => $parsed->tags === [] ? '—' : implode(', ', $parsed->tags),
        ];
    }

    public function importAction(): Action
    {
        return Action::make('import')
            ->label(__('Import recipe'))
            ->action(function (): void {
                $this->import();
            });
    }

    /**
     * Decodes and validates the pasted JSON, refreshing the list of unresolved values.
     */
    private function parse(): ParsedRecipe
    {
        $json = trim((string) ($this->data['json'] ?? ''));

        // AI models routinely wrap the answer in a markdown code fence.
        $json = (string) preg_replace('/^```[a-z]*\s*|\s*```$/i', '', $json);

        // Swiss spelling (RECIPE_SPELLING) also for pasted JSON and drafts, like the AI import.
        $decoded = SwissSpelling::enabled() ? json_decode($json, true) : null;

        if (is_array($decoded)) {
            $json = (string) json_encode(SwissSpelling::recipe($decoded), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        }

        try {
            $this->parsed = app(RecipeJsonValidator::class)->validate($json);
        } catch (ValidationException $exception) {
            throw ValidationException::withMessages([
                'data.json' => $exception->validator->errors()->all(),
            ]);
        }

        $report = app(RelationResolver::class)->resolve($this->parsed, user());

        $this->unresolved = array_map(
            fn (UnresolvedValue $value): array => [
                'key' => $value->key(),
                'type' => $value->type->value,
                'value' => $value->value,
                // The name is editable here: a value longer than allowed can be shortened before creating it.
                'canCreate' => $value->type->canBeCreatedBy(user()),
                'createsRequest' => $value->type->canBeCreatedBy(user()) && $value->type->createsRequest(user()),
                'canOmit' => $value->type->isOmittable(),
                'suggestions' => $value->suggestions,
                'context' => $value->context,
                'preselectedId' => $value->preselectedId(),
            ],
            $report->unresolved
        );

        $this->preselectDecisions();

        $this->scopeLookups = [];

        foreach (['cookbook' => LookupType::Cookbook, 'author' => LookupType::Author] as $scope => $type) {
            $value = $scope === 'cookbook' ? $this->parsed->cookbook : ($this->parsed->author !== null && user()?->isAdmin() ? $this->parsed->author : null);

            if ($value !== null) {
                $key = ResolutionReport::key($type, $value);
                $this->scopeLookups[$scope] = ['key' => $key, 'id' => $report->resolved[$key] ?? null];
            }
        }

        if ($this->parsedName !== $this->parsed->name || blank($this->data['name'] ?? null)) {
            $this->data['name'] = $this->parsed->name;
            $this->parsedName = $this->parsed->name;
        }

        $this->jsonPhotos = count($this->parsed->photos);

        $this->summary = $this->buildSummary($this->parsed);

        return $this->parsed;
    }

    /**
     * Every unresolved value needs a decision entry before the review step renders,
     * otherwise its fields have nothing to bind to. Confident suggestions are filled in,
     * without overwriting anything the user already picked.
     */
    private function preselectDecisions(): void
    {
        foreach ($this->unresolved as $item) {
            $key = $this->stateKey($item['key']);
            $decision = $this->data['decisions'][$key] ?? [];

            $decision['id'] ??= $item['preselectedId'];
            $decision['create'] ??= false;
            $decision['name'] ??= $item['value'];

            if ($item['type'] === LookupType::Food->value) {
                $decision['attributes'] ??= $this->foodAttributes($item['value']);
                $decision['conversion'] ??= ['measure' => null, 'density' => null, 'weights' => [], 'season_months' => [], 'storage_months' => []];
            }

            $this->data['decisions'][$key] = $decision;
        }
    }

    public function import(): void
    {
        // Parsed first: it fills the name field the form validates.
        $parsed = $this->parse();

        $this->form->validate();

        $parsed = $parsed->withName((string) $this->data['name']);
        $requested = [];
        $ignored = [];

        // New lookups and the recipe are saved together: a failed import leaves no requests behind.
        $recipe = DB::transaction(function () use ($parsed, &$requested, &$ignored): Recipe {
            [$decisions, $requested, $ignored] = $this->decisions();

            return $this->importRecipe($parsed, $decisions);
        });

        // Kept until it is pruned: the companion app links its entry to the recipe (GET /api/recipe-drafts/{draft}).
        if ($this->draftId !== null) {
            RecipeDraft::markImported($this->draftId, $recipe);
        }

        LookupRequestedMail::notifyAdmins(user(), $requested, $recipe->name);

        if ($ignored !== []) {
            Notification::make()
                ->warning()
                ->title(__('Conversion and season data not saved'))
                ->body(__('These foods already exist, their data stays as it is: :foods', ['foods' => implode(', ', array_unique($ignored))]))
                ->persistent()
                ->send();
        }

        $this->storePhotos($recipe);

        Notification::make()
            ->success()
            ->title(__('Recipe imported'))
            ->body($recipe->name)
            ->send();

        $this->redirect(RecipeResource::getUrl('edit', ['record' => $recipe]));
    }

    /**
     * Adds the photos uploaded and generated on "Resolve" (checked by content, within the photo limit);
     * a failure only warns, the recipe is imported.
     */
    private function storePhotos(Recipe $recipe): void
    {
        $photos = app(RecipePhotos::class);
        $file = collect(Arr::wrap($this->data['photo'] ?? []))->first(fn (mixed $file): bool => $file instanceof UploadedFile);
        $userId = (int) user()?->getKey();

        $binaries = [];

        if ($file !== null) {
            $binaries[] = [(string) file_get_contents((string) $file->getRealPath()), false];
        }

        if ($this->aiPhoto !== null && ($binary = $photos->importPhoto($userId, $this->aiPhoto)) !== null) {
            $binaries[] = [$binary, true];
        }

        foreach ($binaries as [$binary, $ai]) {
            try {
                $photos->add(
                    $recipe,
                    $binary,
                    $photos->extension($binary, RecipePhotos::MAX_DOWNLOAD_BYTES),
                    $ai ? (string) config('services.openai.image_source') : null,
                    $ai,
                    $ai ? 'ai' : '',
                );
            } catch (InvalidArgumentException $exception) {
                Notification::make()->warning()->title(__('The photo could not be saved.'))->body(__($exception->getMessage()))->persistent()->send();
            }
        }

        $this->removeAiPhoto();
    }

    /**
     * The chosen id per lookup key (null to omit), creating the values the user asked for.
     *
     * @return array{0: array<string, int|null>, 1: array<int, array{type: string, value: string}>, 2: list<string>} decisions, requested values and foods whose conversion data was not stored
     *
     * @throws ValidationException
     */
    private function decisions(): array
    {
        $resolver = app(RelationResolver::class);
        $decisions = [];
        $requested = [];
        $ignored = [];
        $handled = [];

        foreach ($this->unresolved as $item) {
            $type = LookupType::from($item['type']);
            $state = $this->data['decisions'][$this->stateKey($item['key'])] ?? [];

            $omitted = $this->isOmitted($item, $state)
                || $this->isObsolete($item, fn (string $path): mixed => data_get($this->data, $path));

            if ($omitted) {
                $decisions[$item['key']] = null;

                continue;
            }

            if (($state['create'] ?? false) === true) {
                if (! $type->canBeCreatedBy(user())) {
                    abort(403);
                }

                $name = $this->newName($item, $state);

                if (mb_strlen($name) > $type->maxLength()) {
                    throw ValidationException::withMessages([
                        'data.decisions.'.$this->stateKey($item['key']).'.name' => __('The name may not be longer than :max characters.', ['max' => $type->maxLength()]),
                    ]);
                }

                $conversion = $type === LookupType::Food ? $this->validatedConversion($state, $name) : null;

                // An existing entry with that name is used instead (create() matches first, also in the
                // trash and other users' requests); a name given twice is created once, the first one's data wins.
                $id = $resolver->create($type, $name, user());
                $decisions[$item['key']] = $id;

                if (! $resolver->wasCreated($type, $id) || isset($handled[$type->value][$id])) {
                    if ($conversion !== null && ! FoodConversions::isEmpty($conversion)) {
                        $ignored[] = $name;
                    }

                    continue;
                }

                $handled[$type->value][$id] = true;

                if ($conversion !== null) {
                    app(FoodConversions::class)->apply(Food::query()->findOrFail($id), $conversion);
                }

                if ($type->createsRequest(user())) {
                    $requested[] = ['type' => $type->value, 'value' => $name];
                }

                continue;
            }

            $id = $state['id'] ?? null;

            if (! is_numeric($id)) {
                if ($type->isOptional()) {
                    $decisions[$item['key']] = null;

                    continue;
                }

                throw ValidationException::withMessages([
                    'data.decisions' => __('Please resolve :type ":value".', [
                        'type' => $type->label(),
                        'value' => $item['value'],
                    ]),
                ]);
            }

            $decisions[$item['key']] = (int) $id;
        }

        return [$decisions, $requested, $ignored];
    }

    /**
     * The conversion and season fields of a new food checked again on the server (the form checks them first).
     *
     * @param  array<string, mixed>  $state
     * @return array{measure: Measure|null, density: float|null, weights: array<int, float>, season_months: list<int>, storage_months: list<int>}
     *
     * @throws ValidationException
     */
    private function validatedConversion(array $state, string $name): array
    {
        try {
            return app(FoodConversions::class)->validate((array) ($state['conversion'] ?? []), user(), $name);
        } catch (ValidationException $exception) {
            $messages = $exception->validator->errors()->all();

            Notification::make()->danger()->title(__('Recipe could not be imported'))->body(implode(' ', $messages))->persistent()->send();

            throw ValidationException::withMessages(['data.decisions' => $messages]);
        }
    }

    /**
     * @param  array<string, int|null>  $decisions
     *
     * @throws ValidationException
     */
    private function importRecipe(ParsedRecipe $parsed, array $decisions): Recipe
    {
        $cookbookId = $this->data['cookbook_id'] ?? null;

        try {
            return app(RecipeImporter::class)->import(
                $parsed,
                user(),
                $decisions,
                cookbookId: $cookbookId !== null ? (int) $cookbookId : null,
                isPublic: (bool) ($this->data['is_public'] ?? true),
            );
        } catch (ValidationException $exception) {
            $messages = $exception->validator->errors()->all();

            Notification::make()
                ->danger()
                ->title(__('Recipe could not be imported'))
                ->body(implode(' ', $messages))
                ->persistent()
                ->send();

            throw ValidationException::withMessages([
                'data.json' => $messages,
            ]);
        }
    }

    /**
     * Lookup keys contain dots and colons, which Livewire would read as nesting.
     */
    private function stateKey(string $key): string
    {
        return md5($key);
    }
}
